import type { LoggerService } from "@nestjs/common";
import type { LogLevel } from "../config/config";
import { describeError, sanitizeText, stackFrames } from "./sanitize";

const SEVERITY: Record<LogLevel, number> = {
  debug: 10,
  info: 20,
  warn: 30,
  error: 40,
};

/**
 * Keys that may carry personal data or secrets. Values under them are never written,
 * whatever their nesting depth. Callers should still avoid passing such fields at all.
 */
const SENSITIVE_KEY =
  /pass(word)?|secret|token|authorization|cookie|session|e-?mail|phone|whatsapp|cpf|document|address|^ip$|user-?agent|^name$|fullname|customername/i;

export type LogFields = Record<string, unknown>;
export type LogSink = (line: string) => void;

/** Fields whose values are generated by the API itself and kept verbatim. */
const TRUSTED_KEYS = new Set(["requestId"]);

/**
 * Masks values under sensitive keys and sanitizes every other string, at any depth.
 * Errors are reduced to their type and stack frames.
 */
export function redact(value: unknown, depth = 0): unknown {
  if (depth > 5) return "[TRUNCATED]";
  if (typeof value === "string") return sanitizeText(value);
  if (value instanceof Error) return describeError(value);
  if (Array.isArray(value)) return value.map((item) => redact(item, depth + 1));
  if (value && typeof value === "object") {
    return Object.fromEntries(
      Object.entries(value).map(([key, item]) => [
        key,
        SENSITIVE_KEY.test(key)
          ? "[REDACTED]"
          : TRUSTED_KEYS.has(key) && typeof item === "string"
            ? item
            : redact(item, depth + 1),
      ]),
    );
  }
  return value;
}

/**
 * One JSON object per line on stdout, for `docker compose logs` and any log shipper.
 * Every path sanitizes: `msg` is free text and may come from Nest or a library, so it
 * goes through the same masking as field values.
 */
export class JsonLogger implements LoggerService {
  constructor(
    private readonly level: LogLevel,
    private readonly sink: LogSink = (line) =>
      process.stdout.write(`${line}\n`),
  ) {}

  write(level: LogLevel, msg: string, fields: LogFields = {}): void {
    if (SEVERITY[level] < SEVERITY[this.level]) return;
    const entry: LogFields = {
      time: new Date().toISOString(),
      level,
      msg: sanitizeText(msg),
    };
    // Reserved keys always describe the entry itself; fields cannot overwrite them.
    for (const [key, value] of Object.entries(redact(fields) as LogFields)) {
      if (!(key in entry)) entry[key] = value;
    }
    this.sink(JSON.stringify(entry));
  }

  // LoggerService adapter. Nest calls (message, ...optionalParams, context?); the
  // message can be a string, an Error or any object coming from a library.
  log(message: unknown, ...params: unknown[]): void {
    this.adapt("info", message, params);
  }
  error(message: unknown, ...params: unknown[]): void {
    this.adapt("error", message, params);
  }
  warn(message: unknown, ...params: unknown[]): void {
    this.adapt("warn", message, params);
  }
  debug(message: unknown, ...params: unknown[]): void {
    this.adapt("debug", message, params);
  }
  verbose(message: unknown, ...params: unknown[]): void {
    this.adapt("debug", message, params);
  }
  fatal(message: unknown, ...params: unknown[]): void {
    this.adapt("error", message, params);
  }

  private adapt(level: LogLevel, message: unknown, params: unknown[]): void {
    const fields: LogFields = {};
    const last = params[params.length - 1];
    const context =
      typeof last === "string" && !looksLikeStack(last) ? last : undefined;
    if (context) fields.context = context;

    // Nest's error(message, stack, context): keep the frames, drop the message line.
    const stack = params.find(
      (param): param is string =>
        typeof param === "string" && looksLikeStack(param),
    );
    if (stack) fields.frames = stackFrames(stack);

    let msg: string;
    if (message instanceof Error) {
      // An Error's message may carry SQL or input values: log only type and frames.
      const { errorType, frames } = describeError(message);
      msg = "error";
      fields.errorType = errorType;
      fields.frames = frames;
    } else if (typeof message === "string") {
      msg = message;
    } else {
      msg = "structured log";
      fields.data = message;
    }
    this.write(level, msg, fields);
  }
}

const looksLikeStack = (text: string): boolean => /\n\s*at /.test(text);
